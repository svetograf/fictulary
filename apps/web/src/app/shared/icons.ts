import { addIcons } from 'ionicons';
import {
  alertCircleOutline,
  arrowBack,
  arrowForward,
  arrowUndoOutline,
  bookOutline,
  caretDown,
  checkmark,
  checkmarkCircleOutline,
  chevronBack,
  chevronForward,
  clipboardOutline,
  close,
  cloudUploadOutline,
  documentTextOutline,
  helpCircleOutline,
  languageOutline,
  libraryOutline,
  logOutOutline,
  personCircleOutline,
  schoolOutline,
  trashOutline,
} from 'ionicons/icons';

/**
 * Registers the icons that templates name, e.g. `<ion-icon name="close">`.
 * Standalone Ionic bundles only the icons registered here.
 */
export function registerIcons(): void {
  addIcons({
    alertCircleOutline,
    arrowBack,
    arrowForward,
    arrowUndoOutline,
    bookOutline,
    caretDown,
    checkmark,
    checkmarkCircleOutline,
    chevronBack,
    chevronForward,
    clipboardOutline,
    close,
    cloudUploadOutline,
    documentTextOutline,
    helpCircleOutline,
    languageOutline,
    libraryOutline,
    logOutOutline,
    personCircleOutline,
    schoolOutline,
    trashOutline,
  });
}
